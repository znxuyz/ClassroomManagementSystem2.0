  /* ---------- 狀態用的小圖示(點名、作業繳交那幾顆) ----------
     本來是「✓ ⏰ ✕」混著字型符號與彩色 emoji —— 三顆並排,
     粗細與重心完全對不起來,而且 ⏰ 在不同系統長得不一樣。 */
