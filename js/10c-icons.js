  /* 班級管理:兩個人。一大一小,是「一班人」不是「一個使用者」 */
  class: '<circle cx="9" cy="8" r="3"/><path d="M3.5 19c0-3 2.5-5 5.5-5s5.5 2 5.5 5"/>'
       + '<circle cx="17.5" cy="9.5" r="2.2"/><path d="M16 14.4c2.6-.3 4.5 1.6 4.5 4.6"/>',

  /* 兌換商店:禮物盒。橫的緞帶 + 中間的結 */
  shop: '<rect x="3.5" y="9" width="17" height="10.5" rx="1.8"/><path d="M2.5 9h19"/>'
      + '<path d="M12 9v10.5"/>'
      + '<path d="M12 9c-1.2-2.2-2.4-3.5-3.8-3.5A1.9 1.9 0 0 0 8 9z"/>'
      + '<path d="M12 9c1.2-2.2 2.4-3.5 3.8-3.5A1.9 1.9 0 0 1 16 9z"/>',

  /* 學習挑戰:六邊形。和蜂巢戰紀同一個形狀,一看就知道是同一件事 */
  challenge: '<path d="M12 3.2l7.2 4.2v8.4L12 20.8 4.8 16.6V7.4z"/><path d="M12 8.6l3.6 2.1v4.2L12 17l-3.6-2.1v-4.2z"/>',

  /* 數據成果:長條圖。由矮到高,讀起來是「成長」而不是三根隨機的柱子 */
  data: '<path d="M4 20h16"/><path d="M7.5 20v-4"/><path d="M12 20v-8"/><path d="M16.5 20v-12"/>',

  /* 使用說明:問號。圓圈裡的問號比書本更直接 */
  help: '<circle cx="12" cy="12" r="8.5"/>'
